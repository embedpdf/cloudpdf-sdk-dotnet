    /// <summary>
    /// A file that decodes past the server's limit is refused (PayloadTooLarge).
    /// </summary>
    /// <example><code>
    /// await client.Doc.Attachments.DownloadAsync(
    ///     new DownloadAttachmentsRequest
    ///     {
    ///         DocId = "docId",
    ///         LayerName = "layerName",
    ///         FileKey = "fileKey",
    ///     }
    /// );
    /// </code></example>
    public WithRawResponseTask<global::System.IO.Stream> DownloadAsync(
        DownloadAttachmentsRequest request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    )
    {
        return new WithRawResponseTask<global::System.IO.Stream>(
            DownloadAsyncCore(request, options, cancellationToken)
        );
    }

    /// <summary>
    /// A file-attachment annotation's file is listed with the annotation; read its bytes with `doc.annotations.readFile`.
    /// </summary>
    /// <example><code>
    /// await client.Doc.Attachments.ListAsync(
    ///     new ListAttachmentsRequest { DocId = "docId", LayerName = "layerName" }
    /// );
    /// </code></example>
    public WithRawResponseTask<AttachmentList> ListAsync(
        ListAttachmentsRequest request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    )
